n5= int(input("Введите 5 число"))
numbers = [n1, n2, n3, n4, n5]

if len(numbers) == len(set(numbers)):
    print("Все числа уникальны")
else:
    print("Есть повторяющиеся числа")

even_count = 0

negative_count = 0
interval_count = 0
for number in numbers:
    if number % 2 == 0: even_count += 1
    if number < 0:
        negative_count += 1

    if -256 <= number <= 1024:
        interval_count += 1
print("Количество чётных чисел:", even_count)
print("Количество отрицательных чисел:", negative_count)
print("Количество чисел в промежутке [-256; 1024]:", interval_count)

